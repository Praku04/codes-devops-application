/** SIPOC / process flow / swimlane — three views of one extracted process model. */
export type DiagramKind = 'sipoc' | 'flow' | 'swimlane';

/**
 * What a follow-up is allowed to change.
 *
 * `all` revises the shared process model, so all three views are redrawn and stay in agreement —
 * the only way to change what the process *is*. A single kind re-lays out that one picture and
 * leaves the model alone, which is why "only this diagram" cannot produce three views that
 * disagree: the process behind them never moved.
 */
export type DiagramScope = 'all' | DiagramKind;

/**
 * SDD.md §3.2's three architectural views — a different artefact from `DiagramKind`.
 *
 * The blueprint is the business process being automated and carries an approved version;
 * these are the software architecture as the current design describes it, so they have no
 * version and are redrawn whenever the design changes. Mirrors `ARCH_KINDS` in
 * `backend/app/services/diagrams/architecture.py`.
 */
export type ArchitectureKind = 'logical' | 'development' | 'deployment';

/**
 * The two formats SDD.md downloads as. Mirrors `DOC_FORMATS` in
 * `backend/app/services/export/documents.py`, which parses the markdown once and emits both —
 * so the PDF and the DOCX are the same document, laid out the same way this app previews it.
 */
export type DocumentFormat = 'pdf' | 'docx';

/*
 * Narrowing guards for the two kinds above.
 *
 * `ac-diagram-viewer` shows both families — the blueprint and SDD §3.2's architecture views —
 * so the id it emits when the reader switches view is a plain string rather than either union.
 * These are how a caller gets back to its own kind: one guard each, listing the values once,
 * instead of a cast at every call site that would happily pass `'sipoc'` to an architecture
 * lookup.
 */
export function isDiagramKind(value: string): value is DiagramKind {
  return value === 'sipoc' || value === 'flow' || value === 'swimlane';
}

export function isArchitectureKind(value: string): value is ArchitectureKind {
  return value === 'logical' || value === 'development' || value === 'deployment';
}

