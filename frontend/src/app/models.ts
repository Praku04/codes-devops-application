export interface DiagramRevision {
  version: number;
  instruction: string;
  summary: string;
  /**
   * What this revision was allowed to touch. Absent on revisions recorded before the choice
   * existed — those all redrew everything, so a missing value reads as `all`.
   */
  scope?: DiagramScope | string;
  created_at?: string | null;
  /**
   * True when this version's diagrams can still be drawn.
   *
   * Only the last few versions keep the views needed to redraw them (see `HISTORY_LIMIT` in
   * the backend), so an old entry stays in the list as a record of what changed but has no
   * images behind it.
   */
  viewable?: boolean;
}

export interface DiagramImage {
  kind: DiagramKind;
  /** True pixel width of the PNG. Divide by `scale` for the size it is meant to be read at. */
  width: number;
  height: number;
  bytes: number;
  /** Device pixels per layout pixel — 2 means the PNG is drawn at twice its reading size. */
  scale?: number;
}

